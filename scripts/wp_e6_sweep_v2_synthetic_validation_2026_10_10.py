#!/usr/bin/env python3
"""WP-E6-SWEEP design v2 — synthetic injection–recovery on the REAL emulator. No real data vector is read or fitted.

ENGINEERING / DESIGN (not TEST, not FIT). Truth vectors are generated by the same v2 predictor the sweep uses
(emulator × pixel × (1 + s·g) × patchy, K1 at the C4 k_eff). Covariance is the C4 aggregate plus the pinned V2 K2 term.
Three truths: (A) s = 1 noiseless (upstream's own amplitude), (B) s = 2.5 noiseless, (C) s = 1 with one fixed-seed noise
draw from the covariance. Each is swept over a small grid containing the truth cell.

Needs the gitignored emulator tree. Writes data/derived/wp_e6_sweep_v2_synthetic_validation_2026_10_10.json before printing.
    ~/venv/bin/python scripts/wp_e6_sweep_v2_synthetic_validation_2026_10_10.py
"""
import json
import sys
import warnings
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "pipeline"))
sys.path.insert(0, str(ROOT / "phase1_work" / "agent1_emulator"))
import emu_predict as E  # noqa: E402
import keff  # noqa: E402
import sweep  # noqa: E402
import sweep_corrections as sc  # noqa: E402

OUT = ROOT / "data/derived/wp_e6_sweep_v2_synthetic_validation_2026_10_10.json"
REF = ROOT / "data/derived/wp_e6_grid_controls_report_2026_07_28.json"
M_GRID = np.array([-22.5, -22.0, -21.0])
F_GRID = np.array([0.1, 0.2, 0.6])
TRUTH = dict(m=-22.0, f=0.2)


def main():
    pack = E.load()
    corr = sc.load_corrector()
    agg = json.load(open(keff.V2.agg_json))
    k_eff = np.asarray(agg["k_eff_s_per_km"])
    cov9 = np.load(keff.V2.agg_npy)
    cov_sys = keff.augmented_covariance(cov9, keff.V2.precheck_json, keff.V2)
    med = json.load(open(REF))["igm_nuisance_point"]
    nuis = dict(zrei=med["zrei"], ha=med["ha"], hs=med["hs"], taueff=med["taueff"])

    def native(m, f, zrei, ha, hs, taueff):
        return E.predict_pk(pack, m, f, zrei, ha, hs, taueff, "4.2")

    pred = sweep.make_predictor_v2(native, k_eff, corr)
    rng = np.random.default_rng(20261010)
    cases = [("A_s1_noiseless", 1.0, False), ("B_s2p5_noiseless", 2.5, False), ("C_s1_noisy", 1.0, True)]
    rec = {"label": "SYNTHETIC-VALIDATION — emulator-generated; not exclusion, not FIT, not TEST; no real vector read",
           "generated_utc": datetime.now(timezone.utc).isoformat(), "truth_cell": TRUTH, "truth_nuisance": nuis,
           "grid": {"m": M_GRID.tolist(), "f": F_GRID.tolist()}, "cases": {}}
    for name, s_true, noisy in cases:
        data = pred(TRUTH["m"], TRUTH["f"], nuis["zrei"], nuis["ha"], nuis["hs"], nuis["taueff"], s_true)
        if noisy:
            data = data + np.linalg.cholesky(cov_sys) @ rng.standard_normal(9)
        out = ROOT / f"data/derived/_tmp_{name}.json"
        r = sweep.run_sweep(data, cov_sys, pred, "synthetic", out, m_grid=M_GRID, f_grid=F_GRID, design="v2")
        out.unlink(missing_ok=True)
        cells = {f"{c['m']}_{c['f']}": c for c in r["cells"]}
        tc = cells[f"{TRUTH['m']}_{TRUTH['f']}"]
        grid_min = r["grid_minimum"]
        rec["cases"][name] = {
            "s_true": s_true, "noisy": noisy,
            "truth_cell_chi2_min": tc["chi2_min"], "truth_cell_s_fit": tc["best_fit"]["s_siiii"],
            "truth_cell_at_boundary": tc["at_boundary"], "truth_cell_valid": tc["valid_minimum"],
            "grid_minimum": grid_min, "truth_cell_is_grid_minimum": bool(
                grid_min["m"] == TRUTH["m"] and grid_min["f"] == TRUTH["f"]),
            "contour_status": r["contour_status"], "eligibility_rule": r["eligibility_rule"],
            "n_ineligible": len(r["ineligible_cells"]),
            "chi2_all_cells": {k: c["chi2_min"] for k, c in cells.items()},
            "s_fit_all_cells": {k: c["best_fit"]["s_siiii"] for k, c in cells.items()},
        }
    OUT.write_text(json.dumps(rec, indent=1))
    for n, c in rec["cases"].items():
        print(f"{n}: truth chi2 {c['truth_cell_chi2_min']:.4g}, s_fit {c['truth_cell_s_fit']:.3f} (true {c['s_true']}), "
              f"grid min at ({c['grid_minimum']['m']}, {c['grid_minimum']['f']}), truth is min: {c['truth_cell_is_grid_minimum']}, "
              f"ineligible {c['n_ineligible']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
